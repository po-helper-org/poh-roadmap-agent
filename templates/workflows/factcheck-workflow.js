// Шаблон роя фактчека документа для руководства (этап 9 методологии, навык roadmap-09-leadership-pack).
// Только чтение. Каждое утверждение письма или пакета сверяется с картой и источниками.
// Запускается инструментом Workflow; перед запуском загрузи навык workflow-authoring.
// Вызов: Workflow({ script: <этот файл>, args: {
//   doc: '<путь к письму или текст документа>',
//   audience: '<кому: генеральный директор, CPO, CTO>',
//   map: '<корень>/.okr/roadmap/<стрим>',            // можно несколько через запятую
//   src: '<корень>/sources',
// } })
// Возвращает список проблем { quote, problem, evidence, severity, fix, lens }.

export const meta = {
  name: 'exec-doc-factcheck',
  description: 'Адверсариальная проверка документа для руководства: каждое утверждение против карты и источников',
  phases: [{ title: 'Проверка' }],
}

const A = args
const ISS = { type: 'object', properties: { issues: { type: 'array', items: { type: 'object', properties: {
  quote: { type: 'string', description: 'дословный фрагмент документа' }, problem: { type: 'string' }, evidence: { type: 'string', description: 'файл + цитата, подтверждающая проблему' },
  severity: { type: 'string', enum: ['ошибка', 'неточность', 'стиль'] }, fix: { type: 'string', description: 'точная замена' } }, required: ['quote', 'problem', 'evidence', 'severity', 'fix'] } } }, required: ['issues'] }

const BASE = `Документ для руководства (${A.audience}): ${A.doc}. Его отправит PO. Требование PO: «будь предельно внимателен, не выдумывай» — каждое утверждение опирается на источник.
Карта (истина для документа): ${A.map} — backlog/*.md, questions.csv, roadmap.md, journal.csv. Источники карты: ${A.src}/ (WBS, план, реплики PO po-messages.md). Ничего не меняй в файлах. Сообщай только реальные проблемы с доказательством; стиль — только если мешает руководителю понять.`

phase('Проверка')
const LENSES = [
  ['карта', 'Сверь КАЖДОЕ число, дату, имя или роль, название, счётчик (цели, эпики, истории, задачи, вопросы всего/открытых/критичных/без ответственного), статус и формулировку с md-файлами и questions.csv. Пересчитай счётчики сам.'],
  ['источники', 'Сверь каждое утверждение, которого нет дословно в карте (обобщения, «нет своих работ», «окончание задано PO», «N дней», формулировки блокаторов), с WBS, планом и словами PO. Найди утверждения без опоры или противоречащие источникам. Даты — только оценка команды или выполненная работа.'],
  ['читатель', 'Прочитай как руководитель. Найди: формулировки увереннее, чем позволяют источники; противоречия между разделами; жаргон без пояснения; коды WBS, номера задач плана и ссылки на созвоны в тексте; блоки, которых PO не просил («Что нужно от вас»); пропуск важного факта из карты (срыв сроков, критичные вопросы).'],
]
const res = await parallel(LENSES.map(([k, p]) => () => agent(`${BASE}\n\n${p}`, { label: 'проверка: ' + k, phase: 'Проверка', schema: ISS })))
return res.map((r, i) => (r ? r.issues.map(x => ({ ...x, lens: LENSES[i][0] })) : [])).flat()
